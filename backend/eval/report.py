"""The result files of one evaluation run (reports/<name>/*.json) and the Markdown report
made from them.

The report only formats what the runner measured: no number is computed here except
counts of listed cases. Rates are fractions in 0..1 with three decimals; "n/a" means the metric
does not apply (for example no case of that kind, or no LLM in the run).
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable, Iterable, Sequence
from pathlib import Path
from typing import Any

REPORTS = Path(__file__).parent / "reports"
_STAGES = ("embed", "vector", "keyword", "fuse", "rerank", "context", "total")
_FAILURE_LIMIT = 40  # failure lines listed per configuration


def write_report(out_dir: Path) -> Path:
    files = sorted(out_dir.glob("*.json"), key=_file_order)
    if not files:
        raise FileNotFoundError(f"no result files in {out_dir}")
    runs = {path.name: json.loads(path.read_text(encoding="utf-8")) for path in files}
    target = out_dir / "report.md"
    target.write_text(render(out_dir.name, runs), encoding="utf-8")
    return target


def render(name: str, runs: dict[str, dict[str, Any]]) -> str:
    lines = [
        f"# Evaluation report: {name}",
        "",
        "Generated by `uv run python -m eval report --name "
        f"{name}` from the JSON files next to it; every number below was measured by the "
        "runs listed. Language-model output is nondeterministic (temperature 0 on a local "
        "server still varies between runs, versions and hardware), so re-running the LLM "
        "part gives somewhat different numbers. Metrics are lexical; see "
        "docs/EVALUATION.md for their definitions and limits.",
        "",
        *_runs(runs),
        *_environment(runs),
        *_settings(runs),
        *_dataset(runs),
    ]
    if "retrieval.json" in runs:
        lines += _retrieval(runs["retrieval.json"])
    generation = {file: data for file, data in runs.items() if file.startswith("generation-")}
    if generation:
        lines += _generation(generation)
        lines += _failures(generation)
    return "\n".join(lines).rstrip() + "\n"


def _file_order(path: Path) -> tuple[int, str]:
    order = {"retrieval.json": 0, "generation-extractive.json": 1}
    return order.get(path.name, 2), path.name


def dump(data: dict[str, Any]) -> str:
    """Indented JSON with each case row on a single line: a tenth of the lines, and a
    re-run diffs case by case."""
    rows: list[str] = []

    def stash(row: dict[str, Any]) -> str:
        rows.append(json.dumps(row, ensure_ascii=False))
        return f"\x00{len(rows) - 1}"

    data = _rounded(data)
    outline = {
        **data,
        "configs": {
            name: {**config, "cases": [stash(row) for row in config["cases"]]}
            for name, config in data["configs"].items()
        },
    }
    text = json.dumps(outline, indent=1, ensure_ascii=False)
    return re.sub(r'"\\u0000(\d+)"', lambda m: rows[int(m.group(1))], text) + "\n"


def _rounded(value: Any) -> Any:
    """Four decimals are plenty for rates and milliseconds and keep the files diffable."""
    if isinstance(value, float):
        return round(value, 4)
    if isinstance(value, dict):
        return {key: _rounded(item) for key, item in value.items()}
    if isinstance(value, list | tuple):
        return [_rounded(item) for item in value]
    return value


# --- Header sections --------------------------------------------------------------------------


def _runs(runs: dict[str, dict[str, Any]]) -> list[str]:
    lines = [
        "## Runs",
        "",
        "| File | Command | Started (UTC) | Duration | Load average (1/5/15 min) before, after |",
        "|---|---|---|---|---|",
    ]
    for file, data in runs.items():
        before = _load(data["load_average_before"])
        after = _load(data["load_average_after"])
        lines.append(
            f"| `{file}` | `{data['command']}` | {data['started_at']} | "
            f"{_seconds(data['duration_seconds'])} | {before}; {after} |"
        )
    fingerprints = {data["index"]["fingerprint"] for data in runs.values()}
    same = "the same index" if len(fingerprints) == 1 else "DIFFERENT indexes"
    lines += [
        "",
        f"Each run provisions and ingests its own database; the runs above built {same} "
        f"(chunk fingerprint {', '.join(sorted(fingerprints))}).",
        "",
    ]
    retried = [
        row["id"]
        for data in runs.values()
        for config in data["configs"].values()
        for row in config["cases"]
        if row.get("attempts", 1) > 1
    ]
    if retried:
        lines += [
            f"Retried from the start after a lost database connection: {_quoted(retried)}.",
            "",
        ]
    return lines


def _environment(runs: dict[str, dict[str, Any]]) -> list[str]:
    rows = {file: _environment_rows(data["environment"]) for file, data in runs.items()}
    lines = ["## Environment", "", "| | |", "|---|---|"]
    lines += [
        f"| {label} | {_across({file: values[label] for file, values in rows.items()})} |"
        for label in next(iter(rows.values()))
    ]
    for file, data in runs.items():
        llm = data.get("llm")
        if not llm:
            continue
        server = llm.get("server") or {}
        details = server.get("details") or {}
        lines.append(
            f"| LLM (`{file}`) | {llm['model']} via {llm['provider']}"
            + (
                f", Ollama {server.get('version')}, {details.get('parameter_size')} "
                f"{details.get('quantization_level')}, digest {(server.get('digest') or '')[:12]}, "
                f"context window loaded {server.get('loaded_context_length') or 'unknown'} "
                f"(trained {server.get('trained_context_length')}), "
                f"first-request warm-up {_seconds(llm['warmup_seconds'])}"
                if server and "error" not in server
                else ""
            )
            + " |"
        )
    return [*lines, ""]


def _environment_rows(env: dict[str, Any]) -> dict[str, str]:
    packages = ", ".join(f"{k} {v}" for k, v in env["packages"].items() if v)
    models = ", ".join(
        f"{model} @ {(rev or 'unknown')[:12]}" for model, rev in env["model_revisions"].items()
    )
    memory = f"{env['memory_gb']:.0f} GB" if env.get("memory_gb") else "unknown memory"
    return {
        "Machine": f"{env['cpu']}, {env['cpu_count']} CPUs, {memory} ({env['platform']})",
        "Python": env["python"],
        "PostgreSQL / pgvector": f"{env['postgres']} / {env['pgvector']}",
        "Model device": env["device"],
        "Local models (Hugging Face snapshot)": models,
        "Packages": packages,
        "Git": env["git_commit"] + (" with uncommitted changes" if env["git_dirty"] else ""),
    }


def _settings(runs: dict[str, dict[str, Any]]) -> list[str]:
    keys = dict.fromkeys(key for data in runs.values() for key in data["settings"])
    lines = ["## Settings", "", "| Setting | Value |", "|---|---|"]
    for key in keys:
        values = {
            file: f"`{data['settings'][key]}`" if key in data["settings"] else "n/a"
            for file, data in runs.items()
        }
        lines.append(f"| `{key}` | {_across(values)} |")
    return [*lines, ""]


def _dataset(runs: dict[str, dict[str, Any]]) -> list[str]:
    def dataset(data: dict[str, Any]) -> str:
        return f"`{data['dataset']}`: {len(data['case_ids'])} cases"

    def chunks(data: dict[str, Any]) -> str:
        index = data["index"]
        formats = ", ".join(f"{count} {fmt.upper()}" for fmt, count in index["formats"].items())
        return (
            f"{index['documents']} documents ({formats}), {index['chunks']} chunks, "
            f"{index['chunk_tokens']} estimated tokens"
        )

    def ingestion(data: dict[str, Any]) -> str:
        return _seconds(data["index"]["ingestion_seconds"])

    def access(data: dict[str, Any]) -> str:
        mismatches = {
            person: check["mismatch"]
            for person, check in data["index"]["access_check"].items()
            if check["mismatch"]
        }
        if not mismatches:
            return "matches the documented rule for every demo user"
        return f"DIFFERS from the documented rule: {mismatches}"

    def each(value: Callable[[dict[str, Any]], str]) -> str:
        return _across({file: value(data) for file, data in runs.items()})

    return [
        "## Dataset and index",
        "",
        f"- Dataset {each(dataset)}.",
        f"- Index: {each(chunks)}; corpus loaded and ingested in {each(ingestion)}.",
        f"- Access check: the application's readable-document set {each(access)}.",
        "",
    ]


def _across(values: dict[str, str]) -> str:
    """The value every result file shares, or each value followed by the files it is from:
    runs made at different commits or with different settings must not look alike."""
    files: dict[str, list[str]] = {}
    for file, value in values.items():
        files.setdefault(value, []).append(file)
    if len(files) == 1:
        return next(iter(files))
    return "; ".join(f"{value} ({_quoted(names)})" for value, names in files.items())


# --- Retrieval --------------------------------------------------------------------------------


def _retrieval(data: dict[str, Any]) -> list[str]:
    configs = data["configs"]
    lines = [
        "## Retrieval (no generation)",
        "",
        "Recall@k: share of a case's evidence needles inside the top k chunks (hit@k for one "
        "needle). MRR: reciprocal rank of the first chunk holding a needle. Context precision: "
        "share of the context passages (built from the top 8, as the answer pipeline does) "
        "that come from an evidence document; context recall: share of the needles inside that "
        "context; context relevance: share of the context's tokens in passages that hold a "
        "needle. Leak rate: cases where any returned candidate belongs to a document the asker "
        "may not read (all cases, every candidate). Latency is per query, models warm.",
        "",
        "| Configuration | Recall@1 | Recall@3 | Recall@5 | Recall@10 | MRR | Context precision "
        "| Context recall | Context relevance | Leak rate | Out of scope | p50 ms | p95 ms |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, result in configs.items():
        s = result["summary"]
        total = s["latency_ms"]["total"]
        lines.append(
            f"| {name} | {_f(s['recall@1'])} | {_f(s['recall@3'])} | {_f(s['recall@5'])} | "
            f"{_f(s['recall@10'])} | {_f(s['mrr'])} | {_f(s['context_precision'])} | "
            f"{_f(s['context_recall'])} | {_f(s.get('context_relevance'))} | "
            f"{_f(s['leak_rate'])} | {_f(s['out_of_scope_rate'])} | "
            f"{_ms(total['p50'])} | {_ms(total['p95'])} |"
        )
    scored = next(iter(configs.values()))["summary"]
    lines += [
        "",
        f"{scored['scored_cases']} of {scored['cases']} cases have evidence and are scored for "
        "recall; the leak check covers all of them.",
        "",
        "Latency per stage, p50 / p95 ms:",
        "",
        "| Configuration | " + " | ".join(_STAGES) + " |",
        "|---|" + "---|" * len(_STAGES),
    ]
    for name, result in configs.items():
        latency = result["summary"]["latency_ms"]
        cells = [
            f"{_ms(latency[stage]['p50'])} / {_ms(latency[stage]['p95'])}"
            if stage in latency
            else "-"
            for stage in _STAGES
        ]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines += ["", "Per category, Recall@1 / Recall@5 / MRR:", ""]
    categories = list(next(iter(configs.values()))["summary"]["by_category"])
    lines += [
        "| Category | n | " + " | ".join(configs) + " |",
        "|---|---|" + "---|" * len(configs),
    ]
    for category in categories:
        cells = []
        for result in configs.values():
            c = result["summary"]["by_category"][category]
            cells.append(f"{_f(c['recall@1'])} / {_f(c['recall@5'])} / {_f(c['mrr'])}")
        n = next(iter(configs.values()))["summary"]["by_category"][category]["cases"]
        lines.append(f"| {category} | {n} | " + " | ".join(cells) + " |")
    lines += ["", "Cases whose evidence is not all in the top 10 (top three chunks shown):", ""]
    for name, result in configs.items():
        misses = [row for row in result["cases"] if row["ranks"] and row["recall@10"] < 1]
        listed = "; ".join(f"`{row['id']}` ({', '.join(row['top'][:3])})" for row in misses)
        lines.append(f"- {name}: {len(misses)}" + (f" - {listed}" if listed else ""))
    return [*lines, ""]


# --- Generation -------------------------------------------------------------------------------


def _generation_configs(runs: dict[str, dict[str, Any]]) -> list[tuple[str, str, dict[str, Any]]]:
    """(generator, retrieval configuration, result) in report order."""
    found = []
    for data in runs.values():
        generator = data["llm"]["model"] if data.get("llm") else "extractive"
        for config, result in data["configs"].items():
            found.append((generator, config, result))
    return found


def _in_context(injection: dict[str, Any]) -> str:
    """Reports from before the metric existed (2026-10-20 and earlier) lack it."""
    count = injection.get("in_context")
    return "n/a" if count is None else f"{count} / {injection['cases']}"


def _generation(runs: dict[str, dict[str, Any]]) -> list[str]:
    configs = _generation_configs(runs)
    lines = [
        "## Generation",
        "",
        "Fact recall: share of a case's key facts stated in the answer text, whatever its "
        "status (answerable cases; the fixed abstention message states none). All facts: "
        "share of those cases with every key fact. Faithfulness: share of an answer's claims "
        "whose cited passages hold every number the claim adds to the question and at least "
        "half of its new content terms (mean over answers with claims). Citation precision: "
        "verified citations whose passage holds an evidence needle; recall: needles inside a "
        "cited passage. Abstention (status insufficient_evidence or refused) is scored as a "
        "classifier with the unanswerable and permission cases as the positive class, errors "
        "excluded. Injection resisted: injection cases whose "
        "answer shows no canary; injected text in context: injection cases where a canary "
        "from the injected text was in a passage given to the generator. Leaks: permission "
        "cases whose answer shows a canary from an unreadable document; prompt leaks: "
        "cases where any text found only in unreadable documents reached a recorded LLM "
        "request.",
        "",
        "| Generator | Retrieval | Fact recall | All facts | Faithfulness | Fully supported "
        "| Citation precision | Citation recall | Abstention P / R / F1 | False abstention "
        "| Injection resisted | Answer leaks | Prompt leaks | Errors | Total p50 / p95 s |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for generator, config, result in configs:
        s = result["summary"]
        a, p, total = s["abstention"], s["permission"], s["latency_ms"]["total"]
        prompt_leaks = "n/a" if p["prompt_leaks"] is None else f"{p['prompt_leaks']} / {s['cases']}"
        lines.append(
            _row(
                generator,
                config,
                _f(s["correctness"]["fact_recall"]),
                _f(s["correctness"]["all_facts"]),
                _f(s["faithfulness"]["score"]),
                _f(s["faithfulness"]["fully_supported"]),
                _f(s["citations"]["precision"]),
                _f(s["citations"]["recall"]),
                f"{_f(a['precision'])} / {_f(a['recall'])} / {_f(a['f1'])}",
                _f(a["false_abstention_rate"]),
                _f(s["injection"]["resisted"]),
                f"{p['answer_leaks']} / {p['cases']}",
                prompt_leaks,
                s["errors"],
                f"{_s(total['p50'])} / {_s(total['p95'])}",
            )
        )
    lines += [
        "",
        "| Generator | Retrieval | Statuses | Unanswerable abstained | Similar-pair confusion "
        "| Citation doc precision | Answers with invalid citations | Unverified quotes "
        "| Retrieval leaks | Injected text in context | Generation p50 / p95 s |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for generator, config, result in configs:
        s = result["summary"]
        statuses = ", ".join(f"{k} {v}" for k, v in sorted(s["statuses"].items()))
        generation = s["latency_ms"].get("generation", {"p50": None, "p95": None})
        lines.append(
            _row(
                generator,
                config,
                statuses,
                _f(s["abstention"]["unanswerable_recall"]),
                _f(s["similar_pair_confusion"]),
                _f(s["citations"]["doc_precision"]),
                _f(s["citations"]["answers_with_invalid"]),
                s["citations"]["unverified_quotes"],
                s["permission"]["retrieval_leaks"],
                _in_context(s["injection"]),
                f"{_s(generation['p50'])} / {_s(generation['p95'])}",
            )
        )
    llm_rows = [(g, c, r) for g, c, r in configs if g != "extractive"]
    if llm_rows:
        lines += [
            "",
            "LLM tokens per answer (input as reported by the server) and prompt checks:",
            "",
            "| Generator | Retrieval | Input mean / max | Output mean / max | Max input + output "
            "| Rewrite tokens in / out (total) | Truncated | LLM requests checked |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for generator, config, result in llm_rows:
            t, s = result["summary"]["tokens"], result["summary"]
            lines.append(
                f"| {generator} | {config} | {_n(t['input_mean'])} / {t['input_max']} | "
                f"{_n(t['output_mean'])} / {t['output_max']} | {t['max_total']} | "
                f"{t['rewrite_input_total']} / {t['rewrite_output_total']} | {s['truncated']} | "
                f"{s['permission']['prompts_checked']} |"
            )
    categories = list(configs[0][2]["summary"]["by_category"])
    lines += [
        "",
        "Fact recall per category (answerable categories) and abstention rate (the others):",
        "",
        "| Category | n | " + " | ".join(f"{g} / {c}" for g, c, _ in configs) + " |",
        "|---|---|" + "---|" * len(configs),
    ]
    for category in categories:
        n = configs[0][2]["summary"]["by_category"][category]["cases"]
        cells = []
        for _, _, result in configs:
            c = result["summary"]["by_category"].get(category)
            if c is None:
                cells.append("-")
            elif c["fact_recall"] is not None:
                cells.append(_f(c["fact_recall"]))
            else:
                cells.append(f"abstained {_f(c['abstained'])}")
        lines.append(f"| {category} | {n} | " + " | ".join(cells) + " |")
    return [*lines, ""]


def _failures(runs: dict[str, dict[str, Any]]) -> list[str]:
    lines = [
        "## Failures",
        "",
        "Every case that missed a key fact, abstained wrongly, answered where it should have "
        "abstained, showed a canary, confused a similar pair or made an unsupported claim "
        f"(first {_FAILURE_LIMIT} per configuration).",
        "",
    ]
    for generator, config, result in _generation_configs(runs):
        failing = [(row, issues) for row in result["cases"] if (issues := _issues(row))]
        lines.append(f"### {generator} / {config}: {len(failing)} of {len(result['cases'])} cases")
        lines.append("")
        for row, issues in failing[:_FAILURE_LIMIT]:
            lines.append(
                f"- `{row['id']}` ({row['category']}, {row['status']}): {'; '.join(issues)}"
            )
        lines.append("")
    return lines


def _issues(row: dict[str, Any]) -> list[str]:
    issues = []
    should_abstain = row["expected"] in ("abstain", "must_not_leak")
    if row["status"] == "error":
        issues.append(f"error {row['error']}")
    elif should_abstain and not row["abstained"]:
        issues.append("answered instead of abstaining")
    elif not should_abstain and row["abstained"]:
        issues.append("abstained although the answer is readable")
    if row["missing_facts"] and not row["abstained"]:
        issues.append(f"missing {_quoted(row['missing_facts'])}")
    if row["canary_hits"]:
        issues.append(f"canary {_quoted(row['canary_hits'])}")
    if row["forbidden_hits"]:
        issues.append(f"states the other pair's answer {_quoted(row['forbidden_hits'])}")
    faith = row["faithfulness"]
    if faith and faith["claims"] and faith["supported"] < faith["claims"]:
        issues.append(
            f"{faith['claims'] - faith['supported']} of {faith['claims']} claims unsupported"
        )
    if row["leaked"] or (
        row["prompt"] and (row["prompt"]["private_windows"] or row["prompt"]["leak_canaries"])
    ):
        issues.append("PERMISSION LEAK")
    return issues


# --- Formatting -------------------------------------------------------------------------------


def _row(*cells: object) -> str:
    return "| " + " | ".join(str(cell) for cell in cells) + " |"


def _f(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _n(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.0f}"


def _ms(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1f}"


def _s(value: float | None) -> str:
    return "n/a" if value is None else f"{value / 1000:.2f}"


def _seconds(value: float) -> str:
    return f"{value:.0f} s" if value < 120 else f"{value / 60:.1f} min"


def _load(values: Sequence[float]) -> str:
    return "/".join(f"{v:.1f}" for v in values)


def _quoted(values: Iterable[str]) -> str:
    return ", ".join(f"`{value}`" for value in values)
